pub fn seed_kana_mastery(conn: &Connection) -> Result<()> {
    let mut stmt = conn.prepare(
        "INSERT INTO kana_mastery (
            character, romaji, kana_type, alphabet, category, 
            correct_count, wrong_count, total_attempts, correct_attempts, accuracy_percentage
        ) VALUES (?1, ?2, ?3, ?3, ?4, 0, 0, 0, 0, 0.0)
        ON CONFLICT(character) DO UPDATE SET
            romaji = ?2,
            kana_type = ?3,
            alphabet = ?3,
            category = ?4
        WHERE kana_mastery.category IS NULL OR kana_mastery.alphabet IS NULL",
    )?;

    for (character, romaji, alphabet, category) in KANA_SEED_LIST {
        stmt.execute(params![character, romaji, alphabet, category])?;
    }

    Ok(())
}
